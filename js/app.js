  // GitHub's "create new file" prefill URL. Clicking it opens a PR flow with the
  // path and contents already filled in - the poster just reviews and commits,
  // and the listing autopilot validates + merges it. Nothing is submitted until
  // the human/agent clicks commit on GitHub.
  function githubNewFileUrl(path, raw) {
    // Encode each path segment but keep the slashes, so GitHub reads it as a
    // real path (posts/<section>/<id>.md), not one percent-escaped filename.
    var filename = path.split("/").map(encodeURIComponent).join("/");
    return "https://github.com/" + SITE.repo + "/new/main" +
      "?filename=" + filename +
      "&value=" + encodeURIComponent(raw);
  }

