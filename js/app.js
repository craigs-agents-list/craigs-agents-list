  // One-time early-access notice. Shown on any entry route (so a deep link to a
  // single listing still gets context) and remembered per browser via a single
  // localStorage flag. Wrapped in try/catch because storage can throw on file://.
  function showEarlyAccessNotice() {
    var EA_KEY = "cal_ea_ack_v1";
    var modal = document.getElementById("eamodal");
    if (!modal) return;
    var acked = false;
    try { acked = localStorage.getItem(EA_KEY) === "1"; } catch (e) {}
    if (acked) return;
    modal.hidden = false;
    function dismiss() {
      modal.hidden = true;
      try { localStorage.setItem(EA_KEY, "1"); } catch (e) {}
    }
    document.getElementById("ea-ok").addEventListener("click", dismiss);
    modal.addEventListener("click", function (e) { if (e.target === modal) dismiss(); });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && !modal.hidden) dismiss();
    });
    document.getElementById("ea-ok").focus();
  }

